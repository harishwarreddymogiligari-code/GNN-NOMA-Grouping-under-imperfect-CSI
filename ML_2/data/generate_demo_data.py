import os
import numpy as np
import pandas as pd
import config


def generate_noma_dataset(
    num_scenarios: int = 100,
    users_per_scenario: int = 20,
    num_groups: int = 4,
    csi_noise_std: float = 0.15,
    seed: int = 42
) -> pd.DataFrame:
    """
    Generates a realistic wireless scenario dataset for dynamic NOMA user grouping under imperfect CSI.
    
    Each scenario simulates a base station serving multiple users distributed across a cell.
    Channel gains are modeled with distance-dependent path loss and Rayleigh fading.
    Imperfect CSI is generated by introducing Gaussian noise to channel estimates, from which
    csi_error and csi_uncertainty are derived. Ground truth NOMA user groups are assigned
    based on channel gain ordering within each scenario.
    """
    np.random.seed(seed)
    data = []

    global_user_id = 1
    for scenario in range(1, num_scenarios + 1):
        # User distances from base station (10m to 500m)
        distances = np.random.uniform(10.0, 500.0, users_per_scenario)
        # Path loss exponent alpha = 3.0
        path_loss = (10.0 / distances) ** 1.5

        # Small-scale Rayleigh fading (complex Gaussian)
        h_real = np.random.normal(0, 1 / np.sqrt(2), users_per_scenario) * path_loss
        h_imag = np.random.normal(0, 1 / np.sqrt(2), users_per_scenario) * path_loss
        h_gain = np.sqrt(h_real**2 + h_imag**2)

        # SNR in dB (assuming P_tx = 30 dBm, noise = -90 dBm -> offset)
        snr_db = 10 * np.log10(h_gain**2 + 1e-12) + 100.0

        # Channel estimation error and uncertainty (Imperfect CSI)
        # Noise magnitude increases slightly with user distance / lower SNR
        scenario_noise_std = csi_noise_std * (1.0 + distances / 250.0)
        err_real = np.random.normal(0, scenario_noise_std, users_per_scenario)
        err_imag = np.random.normal(0, scenario_noise_std, users_per_scenario)

        h_est_real = h_real + err_real
        h_est_imag = h_imag + err_imag
        h_est_gain = np.sqrt(h_est_real**2 + h_est_imag**2)

        csi_error = np.sqrt(err_real**2 + err_imag**2)
        csi_uncertainty = err_real**2 + err_imag**2

        # Ground truth NOMA User Group assignment based on channel gain quantiles within scenario
        # Sort users by channel gain to assign NOMA pairs/groups (Group 0 = highest gain, Group N-1 = lowest gain)
        gain_ranks = pd.qcut(h_gain, q=num_groups, labels=False, duplicates='drop')
        # Invert so Group 0 is strong channel, Group 3 is weak channel
        user_groups = (num_groups - 1) - gain_ranks

        for u in range(users_per_scenario):
            data.append({
                "scenario_id": scenario,
                "user_id": global_user_id,
                "distance": float(distances[u]),
                "channel_gain": float(h_gain[u]),
                "channel_real": float(h_real[u]),
                "channel_imag": float(h_imag[u]),
                "estimated_channel": float(h_est_gain[u]),
                "estimated_channel_real": float(h_est_real[u]),
                "estimated_channel_imag": float(h_est_imag[u]),
                "snr": float(snr_db[u]),
                "csi_error": float(csi_error[u]),
                "csi_uncertainty": float(csi_uncertainty[u]),
                "user_group": int(user_groups[u])
            })
            global_user_id += 1

    df = pd.DataFrame(data)
    return df


if __name__ == "__main__":
    os.makedirs("data", exist_ok=True)
    out_path = config.DATASET_PATH
    print(f"Generating demo dataset for NOMA User Grouping at: {out_path}...")
    df = generate_noma_dataset(num_scenarios=100, users_per_scenario=20, num_groups=config.NUM_GROUPS)
    df.to_csv(out_path, index=False)
    print(f"Successfully generated {len(df)} user samples across {df['scenario_id'].nunique()} scenarios!")
